"""
DB 연결 담당 모듈.

이 파일이 하는 일은 딱 세 가지입니다.
  1) .env 에 적어둔 DATABASE_URL 로 DB 접속 통로(engine)를 만든다
  2) 세션을 찍어내는 공장(SessionLocal)을 만든다
  3) FastAPI 라우터가 가져다 쓸 의존성 함수 get_db() 를 제공한다

'엔진 / 세션' 용어 정리 (초보자용):
  - engine  : DB 와 연결된 '커넥션 풀'. 프로그램 전체에서 하나만 만들어 계속 재사용한다.
              (요청마다 새로 만들면 매번 접속 비용이 들어서 매우 느려집니다)
  - session : 실제로 쿼리를 날리고 트랜잭션을 관리하는 '작업 창구'.
              요청 하나당 하나씩 새로 열고, 끝나면 반드시 닫아야 한다.
"""

import os

from dotenv import load_dotenv
from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker

# =========================================================================
# 1. .env 읽기
# =========================================================================

# load_dotenv() 는 backend/.env 파일을 찾아서 그 안의 내용을 환경변수로 등록해줍니다.
# 이렇게 하면 비밀번호가 들어간 DB 주소를 코드에 직접 적지 않아도 됩니다.
load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

# 주소가 없으면 어차피 아무것도 못 하므로, 서버가 켜지는 시점에 바로 알려주고 멈춥니다.
# (나중에 엉뚱한 에러 메시지를 보며 헤매는 것보다 이게 훨씬 낫습니다)
if not DATABASE_URL:
    raise RuntimeError(
        "DATABASE_URL 이 없습니다. backend/.env 파일에 DATABASE_URL 을 설정해주세요."
    )


# =========================================================================
# 2. 엔진 만들기
# =========================================================================

engine = create_engine(
    DATABASE_URL,
    # pool_pre_ping: 풀에 보관 중인 커넥션을 꺼내 쓰기 전에 "너 아직 살아있어?" 를
    # 한 번 확인합니다. Neon 같은 서버리스 DB 는 일정 시간 놀고 있으면 연결을 끊어버리기
    # 때문에, 이 옵션이 없으면 오랜만에 요청이 들어올 때 처음 한 번이 에러가 납니다.
    pool_pre_ping=True,
    # pool_recycle: 커넥션을 최대 5분(300초)만 쓰고 새로 맺습니다. 위와 같은 이유로,
    # 중간 장비가 조용히 끊어놓은 연결을 계속 붙잡고 있지 않도록 하는 안전장치입니다.
    pool_recycle=300,
)


# =========================================================================
# 3. 세션 공장(SessionLocal)
# =========================================================================

# sessionmaker 는 '세션을 만드는 함수'를 만들어줍니다.
# 그래서 SessionLocal 자체는 세션이 아니고, SessionLocal() 을 호출해야 세션이 나옵니다.
SessionLocal = sessionmaker(
    bind=engine,
    # autocommit=False: 우리가 commit() 을 직접 불러야 DB 에 반영됩니다.
    #                   (실수로 중간까지만 저장되는 사고를 막아줍니다)
    autocommit=False,
    # autoflush=False: 쿼리를 날릴 때마다 자동으로 DB 에 밀어넣지 않습니다.
    #                  초보자에게는 "내가 commit 한 순간에만 반영된다"가 예측하기 쉽습니다.
    autoflush=False,
)


# =========================================================================
# 4. 의존성 함수 get_db()
# =========================================================================


def get_db():
    """
    요청 하나마다 DB 세션을 열어주고, 그 요청이 끝나면 반드시 닫아주는 함수.

    FastAPI 라우터에서 이렇게 씁니다:

        @app.get("/api/courses")
        def list_courses(db: Session = Depends(get_db)):
            ...  # 여기서 db 를 자유롭게 사용
            # 함수가 끝나면 FastAPI 가 알아서 세션을 닫아줍니다

    ------------------------------------------------------------------
    [중요] 왜 return 이 아니라 yield 를 쓰나?
    ------------------------------------------------------------------
    return 으로 세션을 넘기면, 넘겨준 순간 이 함수는 완전히 끝나버립니다.
    그러면 "이 세션을 나중에 닫아라" 라는 뒷정리 코드를 넣을 자리가 없습니다.

        # 이렇게 하면 close() 를 부를 방법이 없다
        def get_db():
            return SessionLocal()   # 세션이 영원히 안 닫힘 → 커넥션 누수

    yield 는 함수를 '잠시 멈추는' 명령입니다. 동작 순서는 이렇습니다:

        1) 요청이 들어오면 get_db() 가 실행되어 세션을 만든다
        2) yield db 에서 함수가 멈추고, db 를 라우터 함수에게 빌려준다
        3) 라우터 함수가 응답을 만들 때까지 get_db() 는 멈춘 상태로 기다린다
        4) 응답이 끝나면 멈췄던 지점 다음 줄(finally)부터 다시 실행된다
        5) db.close() 로 세션을 반납한다

    finally 에 넣은 이유는, 라우터에서 에러가 터져도 뒷정리는 반드시 실행되어야
    하기 때문입니다. close() 는 세션이 쓰던 커넥션을 풀에 되돌려주는 일을 하는데,
    이걸 빼먹으면 요청이 쌓일수록 커넥션이 고갈되어 서버 전체가 멈춥니다.
    """
    db = SessionLocal()
    try:
        # 여기서 db 를 라우터에게 넘기고 대기한다 (요청 처리 중)
        yield db
    finally:
        # 요청이 정상 종료됐든 에러가 났든, 무조건 세션을 닫는다
        db.close()
